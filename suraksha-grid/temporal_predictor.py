"""
temporal_predictor.py - Daily Spatio-Temporal Crime Risk Forecasting Engine

Uses a Random Forest classifier trained on historical incidents.
Falls back to a transparent rule-based scorer when insufficient data exists.

Output includes:
  - risk_score   : 0–100 probability of crime in a given lat/lon/time slot
  - threat_level : Critical / High / Moderate / Normal
  - feature contributions (top-3 importances when model is trained)
"""

import logging
from datetime import datetime
from typing import Any

import numpy as np
import pandas as pd
from sklearn.ensemble import GradientBoostingClassifier, RandomForestClassifier
from sklearn.model_selection import cross_val_score
from sklearn.preprocessing import StandardScaler

from config import (
    RISK_CRITICAL_THRESHOLD,
    RISK_HIGH_THRESHOLD,
    RISK_MODERATE_THRESHOLD,
)

logger = logging.getLogger(__name__)

FEATURE_COLS = [
    "latitude",
    "longitude",
    "hour",
    "day_of_week",
    "is_weekend",
    "is_festival",
    "is_payday",
    "hour_sin",   # cyclical encoding of hour
    "hour_cos",
    "dow_sin",    # cyclical encoding of day-of-week
    "dow_cos",
]


# ─────────────────────────────────────────────────────────────────────────────
# Feature engineering
# ─────────────────────────────────────────────────────────────────────────────

def _add_temporal_features(df: pd.DataFrame) -> pd.DataFrame:
    """Add derived temporal and cyclical features."""
    df = df.copy()
    df["timestamp"]   = pd.to_datetime(df["timestamp"])
    df["hour"]        = df["timestamp"].dt.hour
    df["day_of_week"] = df["timestamp"].dt.weekday
    df["is_weekend"]  = df["day_of_week"].apply(lambda x: 1 if x >= 5 else 0)

    # Cyclical encoding so the model understands hour 23 is close to hour 0
    df["hour_sin"] = np.sin(2 * np.pi * df["hour"] / 24)
    df["hour_cos"] = np.cos(2 * np.pi * df["hour"] / 24)
    df["dow_sin"]  = np.sin(2 * np.pi * df["day_of_week"] / 7)
    df["dow_cos"]  = np.cos(2 * np.pi * df["day_of_week"] / 7)
    return df


def _build_feature_vector(
    lat: float,
    lon: float,
    hour: int,
    day_of_week: int,
    is_weekend: int,
    is_festival: int,
    is_payday: int,
) -> pd.DataFrame:
    """Construct a single-row feature DataFrame matching FEATURE_COLS."""
    return pd.DataFrame(
        [[
            lat, lon, hour, day_of_week, is_weekend, is_festival, is_payday,
            np.sin(2 * np.pi * hour / 24),
            np.cos(2 * np.pi * hour / 24),
            np.sin(2 * np.pi * day_of_week / 7),
            np.cos(2 * np.pi * day_of_week / 7),
        ]],
        columns=FEATURE_COLS,
    )


# ─────────────────────────────────────────────────────────────────────────────
# Rule-based fallback scorer
# ─────────────────────────────────────────────────────────────────────────────

def _rule_based_score(
    hour: int,
    is_weekend: int,
    is_festival: int,
    is_payday: int,
) -> float:
    """
    Transparent rule-based risk score (0–100).
    Used when the ML model is not yet trained (cold start).
    """
    score = 20.0

    # Time-of-day risk bands
    if 20 <= hour <= 23 or 0 <= hour <= 4:
        score += 30.0  # night / late-night
    elif 17 <= hour <= 19:
        score += 15.0  # rush-hour evening

    # Occasion multipliers
    if is_festival:
        score += 25.0
    if is_payday:
        score += 15.0
    if is_weekend and (18 <= hour <= 23):
        score += 10.0

    return min(score, 99.9)


# ─────────────────────────────────────────────────────────────────────────────
# DailyCrimePredictor
# ─────────────────────────────────────────────────────────────────────────────

class DailyCrimePredictor:
    """
    Spatio-temporal crime risk forecasting engine.

    Training: Random Forest on historical incidents.
    Fallback: Gradient Boosting (ensemble) or rule-based scoring.
    """

    MIN_TRAIN_ROWS = 5  # minimum samples required before ML training

    def __init__(self) -> None:
        self.rf_model  = RandomForestClassifier(n_estimators=100, random_state=42, n_jobs=1)
        self.gb_model  = GradientBoostingClassifier(n_estimators=100, random_state=42)
        self.scaler    = StandardScaler()
        self.is_trained = False
        self.cv_score: float | None = None
        self.feature_importances: dict[str, float] = {}

    # ── Training ──────────────────────────────────────────────────────────────

    def train_model(self, historical_df: pd.DataFrame) -> None:
        """
        Train on historical crime incidents.

        The dataset is treated as fully positive (crime_occurred=1).
        Synthetic negatives are generated by jittering locations / times
        to give the classifier a balanced training set.
        """
        df = _add_temporal_features(historical_df)

        # Ensure target column exists
        if "crime_occurred" not in df.columns:
            df["crime_occurred"] = 1

        # Synthetic negatives: shift hour by ±6 and perturb coordinates
        rng = np.random.default_rng(seed=0)
        neg = df.copy()
        neg["hour"]        = (neg["hour"] + 6) % 24
        neg["latitude"]   += rng.uniform(-0.05, 0.05, len(neg))
        neg["longitude"]  += rng.uniform(-0.05, 0.05, len(neg))
        neg["hour_sin"]    = np.sin(2 * np.pi * neg["hour"] / 24)
        neg["hour_cos"]    = np.cos(2 * np.pi * neg["hour"] / 24)
        neg["crime_occurred"] = 0

        combined = pd.concat([df, neg], ignore_index=True)

        if len(combined) < self.MIN_TRAIN_ROWS:
            logger.warning("[PREDICTOR] Not enough data to train (%d rows). Using rule-based mode.", len(combined))
            return

        X = combined[FEATURE_COLS].fillna(0)
        y = combined["crime_occurred"]

        X_scaled = self.scaler.fit_transform(X)

        self.rf_model.fit(X_scaled, y)
        self.gb_model.fit(X_scaled, y)

        # Cross-validation score (3-fold for small datasets).
        # Skip when training set is very small to avoid joblib spawn issues on Windows.
        cv_folds = min(3, len(combined) // 2)
        if cv_folds >= 2:
            try:
                scores = cross_val_score(
                    self.rf_model, X_scaled, y,
                    cv=cv_folds, scoring="accuracy",
                    n_jobs=1,  # single-process to avoid Windows spawn overhead
                )
                self.cv_score = round(float(scores.mean()), 4)
            except Exception as cv_err:
                logger.debug("[PREDICTOR] CV skipped: %s", cv_err)
                self.cv_score = None
        else:
            self.cv_score = None

        # Feature importances
        self.feature_importances = dict(
            sorted(
                zip(FEATURE_COLS, self.rf_model.feature_importances_),
                key=lambda t: t[1],
                reverse=True,
            )
        )

        self.is_trained = True
        logger.info(
            "[PREDICTOR] Models trained on %d samples. CV accuracy=%.2f%%",
            len(combined),
            self.cv_score * 100,
        )

    # ── Prediction ────────────────────────────────────────────────────────────

    def predict_risk_for_slot(
        self,
        lat: float,
        lon: float,
        target_datetime: str,
        is_festival: int = 0,
        is_payday: int = 0,
    ) -> dict[str, Any]:
        """
        Predict the crime risk score for a geographic point at a specific time.

        Parameters
        ----------
        lat, lon        : WGS-84 coordinates
        target_datetime : ISO-8601 string, e.g. '2026-06-15 21:00:00'
        is_festival     : 1 if a local festival is active on this date
        is_payday       : 1 if this date falls near a salary disbursement day

        Returns
        -------
        dict with risk_score (0–100) and threat_level string.
        """
        dt           = datetime.fromisoformat(target_datetime)
        hour         = dt.hour
        day_of_week  = dt.weekday()
        is_weekend   = 1 if day_of_week >= 5 else 0

        if not self.is_trained:
            base_score = _rule_based_score(hour, is_weekend, is_festival, is_payday)
            return self._format_result(
                lat, lon, target_datetime,
                is_festival, is_payday, base_score,
                method="rule_based",
            )

        X = _build_feature_vector(lat, lon, hour, day_of_week, is_weekend, is_festival, is_payday)
        X_scaled = self.scaler.transform(X)

        # Ensemble: average RF + GB probabilities
        rf_prob = self.rf_model.predict_proba(X_scaled)[0][1]
        gb_prob = self.gb_model.predict_proba(X_scaled)[0][1]
        avg_prob = (rf_prob + gb_prob) / 2.0
        risk_score = round(avg_prob * 100, 2)

        return self._format_result(
            lat, lon, target_datetime,
            is_festival, is_payday, risk_score,
            method="ensemble_rf_gb",
        )

    def predict_grid(
        self,
        lat_min: float, lat_max: float,
        lon_min: float, lon_max: float,
        target_datetime: str,
        is_festival: int = 0,
        is_payday: int = 0,
        grid_steps: int = 5,
    ) -> list[dict[str, Any]]:
        """
        Return risk predictions for an evenly-spaced grid of points
        within a bounding box. Useful for heatmap generation.
        """
        lats = np.linspace(lat_min, lat_max, grid_steps)
        lons = np.linspace(lon_min, lon_max, grid_steps)
        results: list[dict[str, Any]] = []
        for lat in lats:
            for lon in lons:
                results.append(
                    self.predict_risk_for_slot(
                        float(lat), float(lon),
                        target_datetime, is_festival, is_payday,
                    )
                )
        return results

    # ── Internal ──────────────────────────────────────────────────────────────

    def _format_result(
        self,
        lat: float,
        lon: float,
        target_datetime: str,
        is_festival: int,
        is_payday: int,
        risk_score: float,
        method: str,
    ) -> dict[str, Any]:
        """Standardise the prediction output format."""
        if risk_score >= RISK_CRITICAL_THRESHOLD:
            threat = "Critical"
        elif risk_score >= RISK_HIGH_THRESHOLD:
            threat = "High"
        elif risk_score >= RISK_MODERATE_THRESHOLD:
            threat = "Moderate"
        else:
            threat = "Normal"

        result: dict[str, Any] = {
            "latitude":          float(lat),
            "longitude":         float(lon),
            "target_time":       str(target_datetime),
            "occasion_factors":  {"is_festival": bool(is_festival), "is_payday": bool(is_payday)},
            "risk_score":        round(float(risk_score), 2),
            "threat_level":      threat,
            "prediction_method": method,
        }

        if self.cv_score is not None:
            result["model_cv_accuracy"] = f"{float(self.cv_score) * 100:.1f}%"

        if self.feature_importances:
            top3 = {k: round(float(v), 4) for k, v in list(self.feature_importances.items())[:3]}
            result["top_risk_drivers"] = top3

        return result
